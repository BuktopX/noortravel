const fs = require('fs');
const path = require('path');
const { renderHome } = require('../templates/home');
const { renderTour } = require('../templates/tour');

const ROOT = path.resolve(__dirname, '..');
const DATA_DIR = path.join(ROOT, 'data');
const TOURS_DATA_DIR = path.join(DATA_DIR, 'tours');
const TOURS_OUT_DIR = path.join(ROOT, 'tours');

function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, 'utf8'));
}

function writeIfChanged(filePath, content) {
  const normalized = content.replace(/\r\n/g, '\n');
  if (fs.existsSync(filePath)) {
    const existing = fs.readFileSync(filePath, 'utf8').replace(/\r\n/g, '\n');
    if (existing === normalized) return false;
  }
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, normalized, 'utf8');
  return true;
}

function assertCity(cities, id, context) {
  const city = cities[id];
  if (!city) {
    throw new Error(`Unknown city id "${id}" referenced in ${context}. Add it to data/cities.json.`);
  }
  return city;
}

function validateTour(tour, fileName, cities) {
  const required = ['slug', 'name', 'datesShort', 'datesFull', 'departureCity', 'waText', 'seo', 'hero', 'route', 'globe'];
  for (const key of required) {
    if (!tour[key]) {
      throw new Error(`Tour "${fileName}" is missing required field "${key}".`);
    }
  }
  assertCity(cities, tour.departureCity, `${fileName}.departureCity`);
  if (tour.globeHomeCity) assertCity(cities, tour.globeHomeCity, `${fileName}.globeHomeCity`);
  if (tour.globe && tour.globe.flightCity) assertCity(cities, tour.globe.flightCity, `${fileName}.globe.flightCity`);
  (tour.globe?.trainCities || []).forEach((id) => assertCity(cities, id, `${fileName}.globe.trainCities`));
  (tour.globe?.hopCities || []).forEach((id) => assertCity(cities, id, `${fileName}.globe.hopCities`));
}

function defaultTourCamera(from, flight) {
  return {
    startLon: from.lon - 14,
    endLon: flight.lon - 28,
    startLat: Math.max(-45, Math.min(45, from.lat - 12)),
    endLat: Math.max(-45, Math.min(45, flight.lat)),
    panSec: 6,
    finalT: 9
  };
}

function buildGlobeScenes(site, cities, tours) {
  const homeFrom = assertCity(cities, site.home.globeDepartureCity, 'site.home.globeDepartureCity');
  const scenes = {
    home: {
      finalT: 9,
      draggable: true,
      camera: { mode: 'sway', lon: 72, ampLon: 46, speed: 0.07, lat: 24 },
      from: { name: homeFrom.name, lat: homeFrom.lat, lon: homeFrom.lon },
      to: [
        ...tours.map((t) => {
          const c = assertCity(cities, t.globeHomeCity || t.globe.flightCity, `tour:${t.slug}`);
          return {
            name: t.globeLabel || t.name,
            lat: c.lat,
            lon: c.lon,
            href: `tours/${t.slug}.html`
          };
        }),
        ...(site.home.globeSoonCities || []).map((id) => {
          const c = assertCity(cities, id, 'site.home.globeSoonCities');
          return { name: c.name, lat: c.lat, lon: c.lon };
        })
      ]
    }
  };

  for (const tour of tours) {
    const from = assertCity(cities, tour.departureCity, `tour:${tour.slug}`);
    const flight = assertCity(cities, tour.globe.flightCity, `tour:${tour.slug}`);
    const cam = tour.globe.camera || defaultTourCamera(from, flight);

    const scene = {
      finalT: cam.finalT ?? 9,
      camera: {
        startLon: cam.startLon,
        endLon: cam.endLon,
        startLat: cam.startLat,
        endLat: cam.endLat ?? cam.startLat,
        panSec: cam.panSec ?? 6
      },
      from: { name: from.name, lat: from.lat, lon: from.lon },
      flight: {
        name: flight.name,
        lat: flight.lat,
        lon: flight.lon,
        ...(tour.globe.flightSide ? { side: tour.globe.flightSide } : {})
      }
    };

    if (tour.globe.trainCities && tour.globe.trainCities.length) {
      scene.train = tour.globe.trainCities.map((id) => {
        const c = assertCity(cities, id, `tour:${tour.slug}`);
        return [c.lat, c.lon];
      });
      scene.trainLabel = tour.globe.trainLabel || '';
    }

    if (tour.globe.hopCities && tour.globe.hopCities.length) {
      scene.hops = tour.globe.hopCities.map((id) => {
        const c = assertCity(cities, id, `tour:${tour.slug}`);
        const side = tour.globe.hopSides && tour.globe.hopSides[id];
        return { name: c.name, lat: c.lat, lon: c.lon, ...(side ? { side } : {}) };
      });
    }

    scenes[tour.slug] = scene;
  }

  return `// Auto-generated by scripts/build.js from data/site.json, data/cities.json, and data/tours/*.json.\nwindow.NOOR_GLOBE_SCENES = ${JSON.stringify(scenes, null, 2)};\n`;
}

function buildSitemap(site, tours) {
  const baseUrl = site.brand.baseUrl.replace(/\/$/, '');
  const urls = [
    `  <url><loc>${baseUrl}/</loc></url>`,
    ...tours.map((t) => `  <url><loc>${baseUrl}/tours/${t.slug}.html</loc></url>`)
  ];
  return `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls.join('\n')}\n</urlset>\n`;
}

function syncSiteJsContacts(site) {
  const siteJsPath = path.join(ROOT, 'assets', 'site.js');
  let js = fs.readFileSync(siteJsPath, 'utf8');
  js = js
    .replace(/const WHATSAPP_NUMBER = '[^']*';/, `const WHATSAPP_NUMBER = '${site.contacts.whatsappNumber}';`)
    .replace(/const PHONE_NUMBER = '[^']*';/, `const PHONE_NUMBER = '${site.contacts.phone}';`);
  return writeIfChanged(siteJsPath, js);
}

function main() {
  const site = readJson(path.join(DATA_DIR, 'site.json'));
  const cities = readJson(path.join(DATA_DIR, 'cities.json'));

  const tourFiles = fs.readdirSync(TOURS_DATA_DIR).filter((f) => f.endsWith('.json')).sort();
  const tours = tourFiles
    .map((file) => {
      const tour = readJson(path.join(TOURS_DATA_DIR, file));
      validateTour(tour, file, cities);
      return tour;
    })
    .filter((t) => t.published !== false)
    .sort((a, b) => (a.order ?? 999) - (b.order ?? 999));

  writeIfChanged(path.join(ROOT, 'index.html'), renderHome(site, tours));
  for (const tour of tours) {
    writeIfChanged(path.join(TOURS_OUT_DIR, `${tour.slug}.html`), renderTour(site, tours, tour));
  }
  writeIfChanged(path.join(ROOT, 'assets', 'globe-scenes.js'), buildGlobeScenes(site, cities, tours));
  writeIfChanged(path.join(ROOT, 'sitemap.xml'), buildSitemap(site, tours));
  syncSiteJsContacts(site);

  console.log(`Built index.html, ${tours.length} tour pages, assets/globe-scenes.js, and sitemap.xml.`);
}

main();
